#!/usr/bin/env node
// No dependencies. Usage: node tools/backlog.mjs [list | show ID | sync | check]
// sync moves Done/Won't fix tickets to docs/archive/backlog-done.js and regenerates completed_ids.
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const activePath = path.join(root, 'docs/backlog.js');
const archivePath = path.join(root, 'docs/archive/backlog-done.js');
const [command = 'list', arg] = process.argv.slice(2);
const load = (file, name) => {
  const context = {window: {}};
  if (fs.existsSync(file)) vm.runInNewContext(fs.readFileSync(file, 'utf8'), context);
  return context.window[name];
};
const COLUMNS = ['Backlog', 'Ready', 'In progress', 'Blocked', 'Done', "Won't fix"];
const SIZES = ['XS', 'S', 'M', 'L', 'XL'];
const FIELDS = ['id', 'order', 'phase', 'size', 'status', 'depends', 'read', 'title', 'description', 'done_when', 'note'];
const REQUIRED = FIELDS.slice(0, 10);
const terminal = item => ['Done', "Won't fix"].includes(item.status);
const data = load(activePath, 'BACKLOG');
const archive = load(archivePath, 'BACKLOG_ARCHIVE') || [];

const validate = all => {
  const phases = new Set(data.phases.map(p => p.id)), ids = new Set();
  for (const item of all) {
    const extra = Object.keys(item).filter(f => !FIELDS.includes(f)), missing = REQUIRED.filter(f => !(f in item));
    if (extra.length || missing.length) throw Error(item.id+': '+[extra.length && 'unknown field '+extra, missing.length && 'missing '+missing].filter(Boolean).join('; '));
    if (!COLUMNS.includes(item.status) || !phases.has(item.phase) || !SIZES.includes(item.size)) throw Error(item.id+': bad status, phase or size');
    if (ids.has(item.id)) throw Error('Duplicate ID '+item.id);
    ids.add(item.id);
  }
  for (const item of all) for (const d of item.depends) if (!ids.has(d)) throw Error(item.id+': missing dependency '+d);
};

if (command === 'sync' || command === 'check') {
  const moved = data.activities.filter(terminal);
  const closed = [...archive, ...moved].sort((a, b) => a.order - b.order);
  const active = data.activities.filter(item => !terminal(item));
  const ids = closed.filter(item => item.status === 'Done').map(item => item.id).sort();
  validate([...active, ...closed]);
  if (command === 'check') {
    if (moved.length || JSON.stringify(ids) !== JSON.stringify(data.completed_ids)) throw Error('run sync');
  } else {
    data.activities = active;
    data.completed_ids = ids;
    fs.writeFileSync(archivePath, '// Closed tickets. Load only for historical detail. Generated by tools/backlog.mjs sync.\nwindow.BACKLOG_ARCHIVE = '+JSON.stringify(closed, null, 1)+';\n');
    fs.writeFileSync(activePath, '// Active backlog. Models: read this file; completed_ids resolves Done dependencies without archive reads.\n// Complete a ticket here, then run: node tools/backlog.mjs sync\nwindow.BACKLOG = '+JSON.stringify(data, null, 1)+';\n');
  }
  console.log(`${active.length} active, ${closed.length} archived`);
} else if (command === 'show') {
  const item = [...data.activities, ...archive].find(item => item.id === arg);
  if (!item) throw Error('Unknown ticket '+arg);
  console.log(JSON.stringify(item, null, 2));
} else if (command === 'list') {
  const done = new Set(data.completed_ids);
  for (const item of [...data.activities].sort((a, b) => a.order - b.order)) {
    const pending = item.depends.filter(id => !done.has(id));
    console.log(`${item.id}\t${item.status}\t${item.size}\t${pending.length ? 'waiting: '+pending.join(', ') : 'deps done'}\t${item.title}`);
  }
} else throw Error('Usage: node tools/backlog.mjs [list | show ID | sync | check]');
